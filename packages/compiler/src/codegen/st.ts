// IEC 61131-3 Structured Text generator.
//
// Output, in one file:
//   - FUNCTION_BLOCK <Station>: the logic (a CASE state machine and one TON)
//   - PROGRAM <Station>Program: binds the I/O addresses and calls the block
//   - CONFIGURATION: one 20 ms task, as OpenPLC Runtime expects
// For CODESYS, copy only the FUNCTION_BLOCK.
//
// The scan order matches the interlock proof (checker/interlocks.ts):
//   1. runtime monitors, the device position check and E-stop handlers
//      (may stop the machine)
//   2. the current state: its step, or once the step is done its transitions
//   3. state entry for a new state: reset the step and timer, mark devices moving
//   4. every output assigned exactly once from the final state of the scan
//
// State, fault and position numbers are plain integers with comments, the
// most portable form across ST compilers.

import { DEVICE_KINDS } from "../device-kinds.js";
import { formatExpr as tejun, outputsOn, type ExprIR, type StateIR, type StationIR, type TransitionIR } from "../ir.js";
import { VERSION } from "../version.js";

const STOPPED = 0;
const POS_UNKNOWN = 0;
const POS_MOVING = 1;
const RAW_MAX = 65535;

export interface StOptions {
  /** Source path for the header comment. */
  sourcePath: string;
}

export function generateST(ir: StationIR, options: StOptions): string {
  return new Generator(ir, options).run();
}

class Generator {
  private readonly ir: StationIR;
  private readonly options: StOptions;
  private readonly out: string[] = [];
  private indent = 0;
  private readonly stateNo = new Map<string, number>();
  private readonly faultNo = new Map<string, number>();
  /** Device name -> position name -> number. */
  private readonly posNo = new Map<string, Map<string, number>>();

  constructor(ir: StationIR, options: StOptions) {
    this.ir = ir;
    this.options = options;
    this.stateNo.set("Stopped", STOPPED);
    ir.states.forEach((s, i) => this.stateNo.set(s.name, i + 1));
    ir.faults.forEach((f, i) => this.faultNo.set(f, i + 1));
    for (const d of ir.devices) {
      const states = Object.keys(DEVICE_KINDS.get(d.kind)!.states);
      this.posNo.set(d.name, new Map(states.map((s, i) => [s, i + 2])));
    }
  }

  run(): string {
    this.header();
    this.functionBlock();
    this.line("");
    this.program();
    this.line("");
    this.configuration();
    return this.out.join("\n") + "\n";
  }

  // ===== Sections =====

  private header(): void {
    const ir = this.ir;
    this.line(`(* Generated by tejun ${VERSION} from ${comment(this.options.sourcePath)}. Do not edit by hand. *)`);
    this.line("(*");
    this.line(`   Station ${ir.name}${ir.label ? `: ${comment(ir.label)}` : ""}`);
    this.line("");
    this.line(`   States (tj_state):  ${[...this.stateNo].map(([n, i]) => `${i} ${n}`).join(", ")}`);
    this.line(`   Faults (tj_fault):  0 none${ir.faults.map((f, i) => `, ${i + 1} ${f}`).join("")}`);
    for (const [device, positions] of this.posNo) {
      const list = [`${POS_UNKNOWN} unknown`, `${POS_MOVING} moving`, ...[...positions].map(([p, i]) => `${i} ${p}`)];
      this.line(`   Positions (tj_pos_${device}):  ${list.join(", ")}`);
    }
    this.line("*)");
    this.line("");
  }

  private functionBlock(): void {
    const ir = this.ir;
    const initial = ir.states.find((s) => s.name === ir.initialState)!;
    this.line(`FUNCTION_BLOCK ${ir.name}`);
    this.block(() => {
      this.line("VAR_INPUT");
      this.block(() => {
        for (const s of ir.signals.filter((s) => s.direction === "input")) {
          this.line(`${s.name} : ${s.type === "bool" ? "BOOL" : "REAL"};${this.signalComment(s.name)}`);
        }
      });
      this.line("END_VAR");
      this.line("VAR_OUTPUT");
      this.block(() => {
        for (const s of ir.signals.filter((s) => s.direction === "output")) {
          this.line(`${s.name} : ${s.type === "bool" ? "BOOL" : "REAL"};${this.signalComment(s.name)}`);
        }
        this.line(`tj_state : INT := ${this.stateNo.get(initial.name)}; (* current state; starts in ${initial.name} *)`);
        this.line("tj_fault : INT := 0; (* 0 = no fault *)");
      });
      this.line("END_VAR");
      this.line("VAR");
      this.block(() => {
        // The initial state counts as already entered.
        this.line(`tj_last_state : INT := ${this.stateNo.get(initial.name)};`);
        this.line("tj_step_done : BOOL := FALSE;");
        this.line("tj_timer : TON;");
        for (const d of ir.devices) {
          const moving = initial.step?.kind === "device" && initial.step.device === d.name;
          this.line(`tj_pos_${d.name} : INT := ${moving ? POS_MOVING : POS_UNKNOWN}; (* ${d.name} position *)`);
        }
        if (ir.positionCheck) {
          for (const d of ir.devices) {
            this.line(`tj_from_${d.name} : INT := ${POS_UNKNOWN}; (* ${d.name} position when its current move started *)`);
            this.line(`tj_mismatch_${d.name} : TON; (* ${d.name} sensors disagree with its position *)`);
          }
        }
      });
      this.line("END_VAR");
      this.line("");
      this.monitors();
      this.line("");
      this.stateMachine();
      this.line("");
      this.stopOnFault();
      this.line("");
      this.stateEntry();
      this.line("");
      this.outputs();
    });
    this.line("END_FUNCTION_BLOCK");
  }

  private monitors(): void {
    const ir = this.ir;
    this.line("(* ---- Runtime monitors and E-stop: checked every scan ---- *)");
    this.line(`IF tj_state <> ${STOPPED} THEN`);
    this.block(() => {
      for (const i of ir.interlocks) {
        if (i.kind !== "condition") continue;
        this.line(`(* interlock ${comment(tejun(i.condition))} else fault ${i.fault} *)`);
        this.line(`IF tj_fault = 0 AND NOT ${this.expr(i.condition)} THEN`);
        this.block(() => this.line(`tj_fault := ${this.faultNo.get(i.fault)}; (* ${i.fault} *)`));
        this.line("END_IF;");
      }
      this.positionCheck();
      for (const h of ir.handlers.conditions) {
        this.line(`(* on ${comment(tejun(h.condition))} *)`);
        this.line(`IF ${this.expr(h.condition)} THEN`);
        this.block(() => this.gotoState(h.target));
        this.line("END_IF;");
      }
    });
    this.line("END_IF;");
    this.stopOnFault();
  }

  /**
   * Per device, a mismatch is any of: two end sensors ON at once; the device
   * is tracked at an end whose sensor is OFF; or it is moving away from an
   * end whose sensor is still ON. Lasting `debounceMs` raises the fault. The
   * timer runs every scan outside Stopped.
   */
  private positionCheck(): void {
    const check = this.ir.positionCheck;
    if (!check) return;
    for (const d of this.ir.devices) {
      const ends = Object.entries(d.sensors);
      const terms: string[] = [];
      for (let i = 0; i < ends.length; i++) {
        for (let j = i + 1; j < ends.length; j++) terms.push(`(${ends[i]![1]} AND ${ends[j]![1]})`);
      }
      const no = (pos: string) => this.posNo.get(d.name)!.get(pos)!;
      for (const [pos, sensor] of ends) terms.push(`(tj_pos_${d.name} = ${no(pos)} AND NOT ${sensor})`);
      for (const [pos, sensor] of ends) {
        terms.push(`(tj_pos_${d.name} = ${POS_MOVING} AND tj_from_${d.name} = ${no(pos)} AND ${sensor})`);
      }
      this.line(`(* position check: ${d.name} sensors must agree with its tracked position *)`);
      this.line(`tj_mismatch_${d.name}(`);
      this.block(() => {
        this.line(`IN := ${terms[0]}`);
        this.block(() => terms.slice(1).forEach((t, i) => this.line(`OR ${t}${i === terms.length - 2 ? "," : ""}`)));
        this.line(`PT := ${time(check.debounceMs)});`);
      });
      this.line(`IF tj_fault = 0 AND tj_mismatch_${d.name}.Q THEN`);
      this.block(() => this.line(`tj_fault := ${this.faultNo.get(check.fault)}; (* ${check.fault} *)`));
      this.line("END_IF;");
    }
  }

  private stopOnFault(): void {
    this.line("IF tj_fault <> 0 THEN");
    this.block(() => this.gotoState("Stopped"));
    this.line("END_IF;");
  }

  private stateMachine(): void {
    this.line("(* ---- State machine ---- *)");
    this.line("CASE tj_state OF");
    this.block(() => {
      for (const state of this.ir.states) {
        this.line(`${this.stateNo.get(state.name)}: (* ${state.name} *)`);
        this.block(() => this.stateBody(state));
      }
    });
    this.line("END_CASE;");
  }

  private stateBody(state: StateIR): void {
    const step = state.step;
    if (!step) {
      this.transitions(state.transitions);
      return;
    }
    this.line("IF NOT tj_step_done THEN");
    this.block(() => {
      if (step.kind === "hold") {
        this.line(`tj_timer(IN := TRUE, PT := ${time(step.ms)});`);
        this.line("IF tj_timer.Q THEN");
        this.block(() => this.stepDone());
        this.line("END_IF;");
        return;
      }
      if (step.timeout.kind === "within") this.line(`tj_timer(IN := TRUE, PT := ${time(step.timeout.ms)});`);
      this.line(`IF ${step.done} THEN`);
      this.block(() => {
        this.stepDone();
        const pos = this.positionAfter(step.device, step.action);
        this.line(`tj_pos_${step.device} := ${this.posNo.get(step.device)!.get(pos)}; (* ${pos} *)`);
      });
      if (step.timeout.kind === "within") {
        const fault = step.timeout.fault;
        this.line("ELSIF tj_timer.Q THEN");
        this.block(() => this.line(`tj_fault := ${this.faultNo.get(fault)}; (* ${fault} *)`));
      }
      this.line("END_IF;");
    });
    this.line("ELSE");
    this.block(() => this.transitions(state.transitions));
    this.line("END_IF;");
  }

  private stepDone(): void {
    this.line("tj_step_done := TRUE;");
    this.line("tj_timer(IN := FALSE);");
  }

  /** Transitions tried top to bottom; then the wait timeouts, if no default exists. */
  private transitions(transitions: TransitionIR[]): void {
    const timed = transitions.filter((t) => t.timeout?.kind === "within");
    const longest = Math.max(0, ...timed.map((t) => (t.timeout?.kind === "within" ? t.timeout.ms : 0)));
    if (timed.length > 0) this.line(`tj_timer(IN := TRUE, PT := ${time(longest)});`);

    let opened = false;
    for (const t of transitions) {
      if (!t.condition) {
        if (opened) {
          this.line("ELSE");
          this.block(() => this.gotoState(t.target));
          this.line("END_IF;");
        } else {
          this.gotoState(t.target);
        }
        return; // nothing after a bare goto can run
      }
      this.line(`${opened ? "ELSIF" : "IF"} ${this.expr(t.condition)} THEN`);
      this.block(() => this.gotoState(t.target));
      opened = true;
    }
    for (const t of timed) {
      if (t.timeout?.kind !== "within") continue;
      this.line(`ELSIF tj_timer.ET >= ${time(t.timeout.ms)} THEN`);
      const fault = t.timeout.fault;
      this.block(() => this.line(`tj_fault := ${this.faultNo.get(fault)}; (* ${fault} *)`));
    }
    if (opened) this.line("END_IF;");
  }

  private stateEntry(): void {
    this.line("(* ---- State entry: runs once, in the scan the state changes ---- *)");
    this.line("IF tj_state <> tj_last_state THEN");
    this.block(() => {
      this.line("tj_last_state := tj_state;");
      this.line("tj_step_done := FALSE;");
      this.line("tj_timer(IN := FALSE);");
      const moving = this.ir.states.filter((s) => s.step?.kind === "device");
      if (moving.length === 0) return;
      this.line("CASE tj_state OF");
      this.block(() => {
        for (const s of moving) {
          if (s.step?.kind !== "device") continue;
          const d = s.step.device;
          if (this.ir.positionCheck) {
            this.line(`${this.stateNo.get(s.name)}: (* ${s.name}: ${d} moving *)`);
            this.block(() => {
              this.line(`tj_from_${d} := tj_pos_${d};`);
              this.line(`tj_pos_${d} := ${POS_MOVING};`);
            });
          } else {
            this.line(`${this.stateNo.get(s.name)}: tj_pos_${d} := ${POS_MOVING}; (* ${s.name}: ${d} moving *)`);
          }
        }
      });
      this.line("END_CASE;");
    });
    this.line("END_IF;");
  }

  private outputs(): void {
    this.line("(* ---- Outputs: each one assigned exactly once per scan ---- *)");
    for (const signal of this.ir.signals) {
      if (signal.direction !== "output") continue;
      if (signal.type !== "bool") {
        this.line(`(* ${signal.name}: real outputs are not driven by Tejun yet *)`);
        continue;
      }
      const states = this.ir.states.filter((s) => outputsOn(s).includes(signal.name));
      if (states.length === 0) {
        this.line(`${signal.name} := FALSE; (* never ON *)`);
        continue;
      }
      const test = states.map((s) => `(tj_state = ${this.stateNo.get(s.name)})`).join(" OR ");
      this.line(`${signal.name} := ${test}; (* ${states.map((s) => s.name).join(", ")} *)`);
    }
  }

  private program(): void {
    const ir = this.ir;
    const raw = (name: string) => `tj_raw_${name}`;
    this.line(`PROGRAM ${ir.name}Program`);
    this.block(() => {
      // IEC 61131-3 keeps located variables (`AT %…`) and ordinary variables
      // in separate VAR blocks; matiec (OpenPLC) rejects a mixed block.
      this.line("VAR");
      this.block(() => {
        for (const s of ir.signals) {
          if (s.type === "bool") {
            this.line(`${s.name} AT ${s.address} : BOOL;${this.signalComment(s.name, false)}`);
          } else {
            this.line(`${raw(s.name)} AT ${s.address} : UINT; (* ${s.name}, raw 0..${RAW_MAX} *)`);
          }
        }
      });
      this.line("END_VAR");
      this.line("VAR");
      this.block(() => this.line(`tj_station : ${ir.name};`));
      this.line("END_VAR");
      const inputs = ir.signals.filter((s) => s.direction === "input");
      this.line("tj_station(");
      this.block(() => {
        inputs.forEach((s, i) => {
          const value = s.type === "bool" ? s.name : scaled(raw(s.name), s.range);
          this.line(`${s.name} := ${value}${i === inputs.length - 1 ? ");" : ","}`);
        });
      });
      for (const s of ir.signals.filter((s) => s.direction === "output" && s.type === "bool")) {
        this.line(`${s.name} := tj_station.${s.name};`);
      }
    });
    this.line("END_PROGRAM");
  }

  private configuration(): void {
    this.line("CONFIGURATION Config0");
    this.block(() => {
      this.line("RESOURCE Res0 ON PLC");
      this.block(() => {
        this.line("TASK task0(INTERVAL := T#20ms, PRIORITY := 0);");
        this.line(`PROGRAM instance0 WITH task0 : ${this.ir.name}Program;`);
      });
      this.line("END_RESOURCE");
    });
    this.line("END_CONFIGURATION");
  }

  // ===== Helpers =====

  private gotoState(target: string): void {
    this.line(`tj_state := ${this.stateNo.get(target)}; (* ${target} *)`);
  }

  private positionAfter(device: string, action: string): string {
    const kind = DEVICE_KINDS.get(this.ir.devices.find((d) => d.name === device)!.kind)!;
    const done = kind.actions[action]!.done;
    return Object.keys(kind.states).find((s) => kind.states[s] === done)!;
  }

  private signalComment(name: string, withAddress = true): string {
    const s = this.ir.signals.find((x) => x.name === name)!;
    const parts = [
      s.label,
      s.unit,
      s.range ? `${s.range.min}..${s.range.max}` : undefined,
      s.safety ? "safety" : undefined,
      withAddress ? s.address : undefined,
    ].filter((p): p is string => p !== undefined);
    return parts.length > 0 ? ` (* ${comment(parts.join(", "))} *)` : "";
  }

  private expr(e: ExprIR): string {
    switch (e.kind) {
      case "signal":
        return e.name;
      case "device_state":
        return `(tj_pos_${e.device} = ${this.posNo.get(e.device)!.get(e.state)})`;
      case "number":
        return real(e.value);
      case "not":
        return `NOT ${this.expr(e.operand)}`;
      case "and":
        return `(${this.expr(e.left)} AND ${this.expr(e.right)})`;
      case "or":
        return `(${this.expr(e.left)} OR ${this.expr(e.right)})`;
      case "compare": {
        const op = e.op === "==" ? "=" : e.op === "!=" ? "<>" : e.op;
        return `(${this.expr(e.left)} ${op} ${this.expr(e.right)})`;
      }
    }
  }

  private block(body: () => void): void {
    this.indent++;
    body();
    this.indent--;
  }

  private line(text: string): void {
    this.out.push(text === "" ? "" : "  ".repeat(this.indent) + text);
  }
}

/** Linear scaling of a raw 0..65535 word to a declared range. */
function scaled(raw: string, range: { min: number; max: number } | undefined): string {
  const value = `UINT_TO_REAL(${raw})`;
  if (!range) return value;
  const span = `${value} * ${real(range.max - range.min)} / ${real(RAW_MAX)}`;
  return range.min === 0 ? span : `${real(range.min)} + ${span}`;
}

/** An ST REAL literal: always has a decimal point. */
function real(v: number): string {
  if (Number.isInteger(v)) return `${v}.0`;
  const s = String(v);
  return s.includes("e") ? v.toExponential(6).replace("e", "E") : s;
}

function time(ms: number): string {
  return `T#${ms}ms`;
}

/** Keep user text from closing or opening an ST comment. */
function comment(text: string): string {
  return text.replace(/\*\)/g, "* )").replace(/\(\*/g, "( *");
}
